const {withAndroidManifest,withProjectBuildGradle,withInfoPlist}=require('expo/config-plugins');
module.exports=function withNaver(config,{keyId='', enabled=false }={}){
 config=withInfoPlist(config,c=>{c.modResults.LSApplicationQueriesSchemes=[...new Set([...(c.modResults.LSApplicationQueriesSchemes||[]),'nmap'])];if(keyId)c.modResults.NMFNcpKeyId=keyId;return c;});
 config=withAndroidManifest(config,c=>{
  const m=c.modResults.manifest;
  m.queries=m.queries||[];
  if(!m.queries.some(q=>JSON.stringify(q).includes('nmap')))m.queries.push({intent:[{action:[{$:{'android:name':'android.intent.action.VIEW'}}],category:[{$:{'android:name':'android.intent.category.BROWSABLE'}}],data:[{$:{'android:scheme':'nmap'}}]}],package:[{$:{'android:name':'com.nhn.android.nmap'}}]});
  const app=m.application[0];app['meta-data']=app['meta-data']||[];
  app['meta-data']=app['meta-data'].filter(x=>x.$['android:name']!=='com.naver.maps.map.NCP_KEY_ID');
  if(keyId)app['meta-data'].push({$:{'android:name':'com.naver.maps.map.NCP_KEY_ID','android:value':keyId}});
  return c;
 });
 // Modules declare their own Naver Maven repository as well. This injection covers the
 // standard Groovy project generated by Expo; fail loudly if the template changes.
 if(!enabled)return config;
 return withProjectBuildGradle(config,c=>{
  if(c.modResults.contents.includes('repository.map.naver.com'))return c;
  if(c.modResults.language!=='groovy')throw new Error('Review Naver Maven setup for this Gradle template.');
  c.modResults.contents+='\n// First-party Naver SDK repository\nallprojects { repositories { maven { url "https://repository.map.naver.com/archive/maven" } } }\n';
  return c;
 });
};
