export function hasChineseTranslation(english: string): boolean {
  return Object.prototype.hasOwnProperty.call(ZH_TRANSLATIONS, english);
}

/** Legacy remote records keep their English proper name when no Chinese text exists. */
export function t(en: string, ko: string, lang: Language, zh?: string): string {
  if (lang === 'ko') return ko;
  if (lang === 'zh') return zh?.trim() ? zh : hasChineseTranslation(en) ? ZH_TRANSLATIONS[en]! : en;
  return en;
}

export function localize(value: Localized, lang: Language): string {
  return t(value.en, value.ko, lang, value.zh);
}
